class Scanner:
    """Convenience public scanner class for analyzing inputs and requests."""

    def __init__(self, firewall: Optional[Firewall] = None) -> None:
        self.firewall = firewall or Firewall()

    def scan(self, text: str, **kwargs: Any) -> ScanResult:
        """Scans text for prompt injection, secrets, PII, and security threats."""
        return self.firewall.scan(text, **kwargs)

    def scan_request(self, request: ScanRequest) -> ScanResult:
        """Scans a structured ScanRequest."""
        return self.firewall.scan_request(request)


